def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as fh:
        for chunk in iter(lambda: fh.read(1024 * 1024), b""):
            h.update(chunk)
    return h.hexdigest()


def alpha_bounds(image: Image.Image) -> tuple[int, int, int, int]:
    alpha = image.convert("RGBA").getchannel("A")
    return alpha.point(lambda v: 255 if v >= ALPHA_THRESHOLD else 0).getbbox() or (0, 0, 0, 0)


def offset(layer: Image.Image, dx: int, dy: int) -> Image.Image:
    out = Image.new("RGBA", layer.size, (0, 0, 0, 0))
    out.alpha_composite(layer, (int(dx), int(dy)))
    return out


def align_baseline(image: Image.Image, baseline: int) -> Image.Image:
    bounds = alpha_bounds(image)
    if bounds == (0, 0, 0, 0):
        raise ValueError("empty_alpha_after_transform")
    dy = baseline - (bounds[3] - 1)
    return offset(image, 0, dy) if dy else image


def whole_pose(source: Image.Image, source_bounds, angle: float, dx: int = 0) -> Image.Image:
    x0, y0, x1, y1 = source_bounds
    pivot = (int(round((x0 + x1) * 0.5)), int(round(y0 + (y1 - y0) * 0.62)))
    rotated = source.rotate(
        angle,
        resample=Image.Resampling.NEAREST,
        center=pivot,
        expand=False,
        fillcolor=(0, 0, 0, 0),
    )
    posed = offset(rotated, dx, 0) if dx else rotated
    return align_baseline(posed, source_bounds[3] - 1)


def assert_frame(frame: Image.Image, label: str, baseline: int, grounded: bool = True) -> tuple[int, int, int, int]:
    if frame.size != CANVAS:
        raise ValueError(f"{label}:canvas={frame.size}")
    bounds = alpha_bounds(frame)
    if bounds == (0, 0, 0, 0):
        raise ValueError(f"{label}:empty_alpha")
    if bounds[0] <= 0 or bounds[1] <= 0 or bounds[2] >= CANVAS[0] or bounds[3] >= CANVAS[1]:
        raise ValueError(f"{label}:canvas_clip bounds={bounds}")
    if grounded and bounds[3] - 1 != baseline:
        raise ValueError(f"{label}:baseline={bounds[3]-1} expected={baseline}")
    return bounds


def save_family(repo: Path, name: str, frames: list[Image.Image], prefix: str, baseline: int) -> list[dict]:
    folder = repo / "assets/pack_01_characters/lian_wu/frames/c64" / name
    if folder.exists():
        shutil.rmtree(folder)
    folder.mkdir(parents=True, exist_ok=True)
    rows = []
    for index, frame in enumerate(frames, start=1):
        bounds = assert_frame(frame, f"{name}:{index}", baseline)
        path = folder / f"char_lian_wu__{prefix}__f{index:02d}.png"
        frame.save(path, format="PNG", optimize=False, compress_level=9)
        rows.append({
            "index": index,
            "path": path.relative_to(repo).as_posix(),
            "sha256": sha256(path),
            "alpha_bounds": list(bounds),
            "baseline_y": bounds[3] - 1,
        })
    if len({row["sha256"] for row in rows}) != len(rows):
        raise ValueError(f"{name}:duplicate_frames")
    return rows


def generate_c64_families(repo: Path) -> dict:
    neutral_path = repo / NEUTRAL_REL
    stance_path = repo / STANCE_REL
    identity = validate_source(neutral_path)
    if identity["file_sha256"] != NEUTRAL_FILE_SHA or identity["decoded_rgba_sha256"] != CANONICAL_RGBA_SHA:
        raise ValueError("neutral_identity_not_exact_historical")
    if sha256(stance_path) != STANCE_FILE_SHA:
        raise ValueError("combat_stance_hash_mismatch")

    neutral = Image.open(neutral_path).convert("RGBA")
    stance = Image.open(stance_path).convert("RGBA")
    bounds = alpha_bounds(neutral)
    if bounds != CANONICAL_BOUNDS:
        raise ValueError(f"neutral_bounds={bounds} expected={CANONICAL_BOUNDS}")
    baseline = bounds[3] - 1

    # Guard deliberately uses the exact historical combat stance. It is a stable hold,
    # not an invented animation, and is therefore the safest first-playable guard read.
    guard = [align_baseline(stance, baseline)]

    # Grounded evasive slip: short backward translation plus torso/body lean.
    dodge = [
        whole_pose(neutral, bounds, -2.0, -7),
        whole_pose(neutral, bounds, -5.0, -18),
        whole_pose(neutral, bounds, -8.0, -30),
        whole_pose(neutral, bounds, -4.0, -16),
        neutral.copy(),
    ]

    # Hit reaction: compact recoil, stronger recoil, distinct recovery, exact neutral handoff.
    hit = [
        whole_pose(neutral, bounds, 4.0, 8),
        whole_pose(neutral, bounds, 8.0, 17),
        whole_pose(neutral, bounds, 2.0, 4),
        neutral.copy(),
    ]

    # KO: deterministic progressive collapse around the body center, then ground-align.
    ko = [
        whole_pose(neutral, bounds, 12.0, 4),
        whole_pose(neutral, bounds, 30.0, 11),
        whole_pose(neutral, bounds, 52.0, 17),
        whole_pose(neutral, bounds, 72.0, 21),
        whole_pose(neutral, bounds, 90.0, 24),
    ]

    families = {
        "guard": save_family(repo, "guard", guard, "guard", baseline),
        "dodge": save_family(repo, "dodge", dodge, "dodge", baseline),
        "hit": save_family(repo, "hit", hit, "hit", baseline),
        "ko": save_family(repo, "ko", ko, "ko", baseline),
    }

    # The final hit frame is a semantic handoff back to idle. Preserve the exact
    # historical PNG bytes rather than allowing Pillow to re-encode identical pixels.
    hit_handoff = repo / families["hit"][-1]["path"]
    shutil.copyfile(neutral_path, hit_handoff)
    with Image.open(hit_handoff) as opened:
        handoff_bounds = assert_frame(opened.convert("RGBA"), "hit:handoff", baseline)
    families["hit"][-1].update({
        "sha256": sha256(hit_handoff),
        "alpha_bounds": list(handoff_bounds),
        "baseline_y": handoff_bounds[3] - 1,
    })
    if len({row["sha256"] for row in families["hit"]}) != len(families["hit"]):
        raise ValueError("hit:duplicate_frames_after_exact_handoff")
    if families["hit"][-1]["sha256"] != NEUTRAL_FILE_SHA:
        raise ValueError("hit_neutral_handoff_hash")

    metadata = {
        "schema": "tehkne/taijifu-c64-lian-first-playable-families/v1",
        "signature": SIGNATURE,
        "status": "candidate_pending_contact_sheet_review",
        "character_id": "lian_wu",
        "source": {
            "neutral": NEUTRAL_REL.as_posix(),
            "neutral_sha256": NEUTRAL_FILE_SHA,
            "neutral_decoded_rgba_sha256": CANONICAL_RGBA_SHA,
            "combat_stance": STANCE_REL.as_posix(),
            "combat_stance_sha256": STANCE_FILE_SHA,
            "alpha_bounds": list(bounds),
            "baseline_y": baseline,
        },
        "families": families,
        "generation_policy": {
            "redraw": False,
            "global_scale": False,
            "identity_mutation": False,
            "nearest_neighbor_rotation": True,
            "baseline_preserved": True,
            "visual_review_required_before_repo_binary_promotion": True,
        },
    }
    meta = repo / "assets/pack_01_characters/lian_wu/metadata/c64_first_playable_families.json"
    meta.parent.mkdir(parents=True, exist_ok=True)
    meta.write_text(json.dumps(metadata, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    return metadata


def run_existing_generators(repo: Path) -> None:
    for relative in EXISTING_GENERATORS:
        command = [sys.executable, str(repo / relative), "--repo-root", str(repo)]
        print("C64_GENERATOR_RUN", relative)
        result = subprocess.run(command, cwd=repo, text=True)
        if result.returncode != 0:
            raise RuntimeError(f"generator_failed={relative} rc={result.returncode}")


def collect_source_frames(repo: Path, source_dir: str) -> list[Path]:
    frames = sorted((repo / source_dir).glob("*.png"))
    if not frames:
        raise ValueError(f"no_frames={source_dir}")
    return frames


def write_spriteframes(target: Path, animation_files: dict[str, list[Path]], specs: dict[str, tuple[float, bool]]) -> None:
    resources: list[str] = []
    ids: dict[Path, int] = {}
    ext_id = 1
    for name in REQUIRED:
        for frame in animation_files[name]:
            ids[frame] = ext_id
            resources.append(
                f'[ext_resource type="Texture2D" path="res://{frame.as_posix()}" id="{ext_id}"]'
            )
            ext_id += 1
    animations = []
    for name in REQUIRED:
        fps, loop = specs[name]
        rows = ", ".join(
            '{"duration": 1.0, "texture": ExtResource("%d")}' % ids[path]
            for path in animation_files[name]
        )
        animations.append(
            '{"frames": [%s], "loop": %s, "name": &"%s", "speed": %.3f}'
            % (rows, "true" if loop else "false", name, fps)
        )
    text = "\n".join([
        f'[gd_resource type="SpriteFrames" load_steps={ext_id} format=3]',
        "",
        *resources,
        "",
        "[resource]",
        "animations = [%s]" % ",\n".join(animations),
        "",
    ])
    target.write_text(text, encoding="utf-8")


def build_contact_sheet(repo: Path, target: Path, animation_files: dict[str, list[Path]]) -> None:
    thumb = 112
    label_w = 150
    gap = 8
    max_frames = max(len(v) for v in animation_files.values())
    width = label_w + max_frames * (thumb + gap) + gap
    height = len(REQUIRED) * (thumb + 28) + 20
    sheet = Image.new("RGB", (width, height), "white")
    draw = ImageDraw.Draw(sheet)
    font = ImageFont.load_default()
    for row, name in enumerate(REQUIRED):
        y = 10 + row * (thumb + 28)
        draw.text((8, y + 45), name, fill="black", font=font)
        for col, path in enumerate(animation_files[name]):
            image = Image.open(repo / path).convert("RGBA")
            crop = image.crop(alpha_bounds(image))
            crop.thumbnail((thumb, thumb), Image.Resampling.NEAREST)
            tile = Image.new("RGBA", (thumb, thumb), (240, 240, 240, 255))
            tile.alpha_composite(crop, ((thumb - crop.width) // 2, thumb - crop.height))
            sheet.paste(tile.convert("RGB"), (label_w + col * (thumb + gap), y))
            draw.text((label_w + col * (thumb + gap) + 2, y + thumb + 2), f"f{col+1:02d}", fill="black", font=font)
    sheet.save(target, format="PNG", compress_level=9)


def materialize(repo: Path, c64_meta: dict) -> dict:
    target = repo / TARGET_REL
    if target.exists():
        shutil.rmtree(target)
    (target / "animations").mkdir(parents=True, exist_ok=True)

    animation_files: dict[str, list[Path]] = {}
    specs: dict[str, tuple[float, bool]] = {}
    for name in REQUIRED:
        source_dir, fps, loop = ANIMATION_SOURCES[name]
        sources = collect_source_frames(repo, source_dir)
        destination = target / "animations" / name
        destination.mkdir(parents=True, exist_ok=True)
        copied = []
        for index, source in enumerate(sources, start=1):
            out = destination / f"char_lian_wu__{name}__f{index:02d}.png"
            shutil.copyfile(source, out)
            copied.append(out.relative_to(repo))
        animation_files[name] = copied
        specs[name] = (fps, loop)

    resource = target / "lian_wu_first_playable_frames.tres"
    write_spriteframes(resource, animation_files, specs)

    runtime = {
        "schema": "tehkne/taijifu-first-playable-runtime-map/v1",
        "signature": SIGNATURE,
        "animations": {
            name: {
                "path": f"animations/{name}",
                "fps": specs[name][0],
                "loop": specs[name][1],
                "frames": len(animation_files[name]),
            }
            for name in REQUIRED
        },
    }
    manifest = {
        "schema": "tehkne/taijifu-first-playable-lot/v1",
        "signature": SIGNATURE,
        "lot_id": "pack_01_lian_wu_first_playable_lot_01",
        "stage": "C64",
        "status": "candidate_pending_contact_sheet_review",
        "character_id": "lian_wu",
        "source_character_lock_sha256": NEUTRAL_FILE_SHA,
        "source_character_lock_rgba_sha256": CANONICAL_RGBA_SHA,
        "required_animations": list(REQUIRED),
        "animation_count": len(REQUIRED),
        "frame_count": sum(len(v) for v in animation_files.values()),
        "spriteframes": resource.relative_to(repo).as_posix(),
        "c64_families_metadata": "assets/pack_01_characters/lian_wu/metadata/c64_first_playable_families.json",
    }
    approval = {
        "schema": "tehkne/taijifu-first-playable-approval/v1",
        "signature": SIGNATURE,
        "status": "candidate_pending_visual_review",
        "technical_generation": "pass",
        "binary_promotion_allowed": False,
        "required_review_artifact": "c64-lian-first-playable-contact-sheet.png",
    }
    (target / "manifest.json").write_text(json.dumps(manifest, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    (target / "runtime-map.json").write_text(json.dumps(runtime, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    (target / "approval.json").write_text(json.dumps(approval, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")

    checks = []
    for path in sorted(target.rglob("*")):
        if path.is_file() and path.name != "checksums.sha256":
            checks.append(f"{sha256(path)}  {path.relative_to(target).as_posix()}")
    (target / "checksums.sha256").write_text("\n".join(checks) + "\n", encoding="utf-8")

    contact = repo / "c64-lian-first-playable-contact-sheet.png"
    build_contact_sheet(repo, contact, animation_files)

    report = {
        "schema": "tehkne/taijifu-c64-lot01-materialization-report/v1",
        "signature": SIGNATURE,
        "status": "candidate_pending_contact_sheet_review",
        "required_animation_count": len(REQUIRED),
        "frame_count": manifest["frame_count"],
        "animations": {name: len(animation_files[name]) for name in REQUIRED},
        "spriteframes": resource.relative_to(repo).as_posix(),
        "contact_sheet": contact.name,
        "source_exact_historical": True,
        "c64_new_families": {name: len(c64_meta["families"][name]) for name in ("guard", "dodge", "hit", "ko")},
    }
    report_path = repo / "c64-lian-first-playable-report.json"
    report_path.write_text(json.dumps(report, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    return report


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--repo-root", default=".")
    args = parser.parse_args()
    repo = Path(args.repo_root).resolve()
    try:
        run_existing_generators(repo)
        c64_meta = generate_c64_families(repo)
        report = materialize(repo, c64_meta)
    except (OSError, ValueError, RuntimeError) as exc:
        print(f"C64_LOT01=BLOCKED {exc}")
        return 2
    print("C64_LOT01_MATERIALIZATION=PASS")
    print(f"animations={report['required_animation_count']}/10")
    print(f"frames={report['frame_count']}")
    print(f"spriteframes={report['spriteframes']}")
    print("visual_review=PENDING")
    print(f"SIGNATURE={SIGNATURE}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
